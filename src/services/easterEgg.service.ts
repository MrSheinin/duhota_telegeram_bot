export class EasterEggService {
  // Храним ID в виде строк, чтобы избежать проблем с приведением типов BigInt/Number
  private static readonly FRIEND_IDS = {
    FADILA: '7082399720',
    ALBERT: '6771910324',
    FJODOR: '1235005516',
    DIMA: '699812309',
  } as const;

  /**
   * 1. Приветственное сообщение при первой регистрации
   */
  static getRegistrationMessage(telegramId: number | string, firstName: string): string {
    const idStr = String(telegramId);
    switch (idStr) {
      case this.FRIEND_IDS.FADILA:
        return `О, блядь, Фадеев зашёл! Ну хоть один нормальный атлет в этом заведении, а не сопляк с блогерскими мечтами.\n\nКороче, Фадила, ты сам знаешь: 6 дней в неделю ебошим, спину ровно держим. На тебя вся надежда, нахуй, покажи этим подснежникам, как надо пахать! Погнали программу делать.`;
      case this.FRIEND_IDS.ALBERT:
        return `Альберт, блядь, здорово! Ты опять перед залом эту химозную срань — энергетик свой — выпил, нахуй?! Сердце свое посадить хочешь, блядь? Завязывай с этой хуйнёй блять нахуй! Тебе натуральная сила нужна, а не банка ебаных химикатов. Давай, создавай программу и ебошь нормально, а не на стимуляторах!`;
      case this.FRIEND_IDS.FJODOR:
        return `Фидр, блядь, сука, здорово, нахуй! Ты чё, "Пёс на цепи", блядь, совсем в своём СВО все мозги оставил, ебать?! Стоишь, блядь, тупишь в экран, как долбоёб, сообразить нихуя не можешь, куда тыкать, блядь! Завязывай ты с этой хуетой — со своей цепи срываться, в СВО будешь башкой отбитой махать, блядь, а здесь, нахуй ебошить по настоящему надо, сука, блядь, нахуй! Вали в зал, бери железо и качайся, блядь, как нормальный мужик, нахуй! Давай, соображай быстрее своим пробитым кочаном, выбирай программу, блядь, и погнали ебошить!`;
      case this.FRIEND_IDS.DIMA:
        return `Димон, блядь, сука, здорово, нахуй! Ты чё там опять застыл, ебать?! Стоишь, блядь, сопли жуёшь и в экран глазами хлопаешь, как будто тебе в зал первый раз в жизни зайти разрешили, сука! Хватит отмазки в голове крутить, нахуй! Вали в зал, бери штангу и начинай пахать, блядь, а не теории тут разводить! Выбирай программу, сука, и погнали ебошить!`;
      default:
        return `Слышь, ${firstName}.\n\nЯ тут, блядь, чтобы ты нормально отслеживал свои тренировки, смотрел прогресс и не проёбывал дни, нахуй. Никаких соплей и отговорок.\n\nБыстро заходишь в меню, блядь, создаёшь свою первую программу — и погнали ебошить.`;
    }
  }

  /**
   * 2. Сообщение после завершения и сохранения тренировки
   */
  static getWorkoutCompletedMessage(
    telegramId: number | string,
    workoutTitle: string,
    durationMinutes?: number
  ): string {
    const idStr = String(telegramId);
    const timeInfo = durationMinutes ? ` за ${durationMinutes} мин` : '';

    switch (idStr) {
      case this.FRIEND_IDS.FADILA:
        return `🔥 Опа, Фадеев, тренировка "${workoutTitle}" зафиксирована${timeInfo}!\n\nНу вот это по-нашему, по-мужски, блядь! Своё отработал, красава. Вьёбываешь как надо, нахуй! Иди накати 50 грамм овсянки с ягодами — и завтра опять в зал, отдыхать некогда.`;
      case this.FRIEND_IDS.ALBERT:
        return `💪 Альберт, тренировка "${workoutTitle}" зафиксирована${timeInfo}!\n\nНу отработал, красава. Но ты мне скажи: ты это на своей силе сделал или опять энергетика в себя залил, сука, нахуй? Выкинь эту химозу и съешь лучше каши, нахуй, с ягодами, сука и восстанавливайся нормально!`;
      case this.FRIEND_IDS.FJODOR:
        return `✅ Нихуя себе, ебать, "Пёс на цепи", тренировка "${workoutTitle}" зафиксирована${timeInfo}, блядь!\n\nНу вот видишь, нахуй! Когда ты не в СВО со своей цепи рвёшься и тебе в репу каждые два хода не прилетает, блядь, мозги хоть немного соображать начинают, сука! Мощно отработал, красава, блядь! Вот так в зале ебошить надо, нахуй, а не мордой ринг в СВО подметать, блядь! Иди жри кашу, нахуй, и восстанавливайся, пока тебя опять на цепь не посадили, блядь!`;
      case this.FRIEND_IDS.DIMA:
        return `✅ Нихуя себе, ебать! Димон, тренировка "${workoutTitle}" зафиксирована${timeInfo}, блядь!\n\nНу надо же, сука! И фаза луны совпала, и ЦНС не сгорела, и жопа не отвалилась, и даже отмазку придумать не успел, блядь! Мощно отработал, красава, нахуй! Вот так надо пахать всегда, а не сопли по грифу размазывать, блядь! Пошел быстро жрать свою кашу и восстанавливаться, пока ты опять херню какую-то про "перетренированность" выдумывать не начал, нахуй!`;
      default:
        return `Всё, блядь, тренировка "${workoutTitle}" зафиксирована${timeInfo}.\n\nСвоё на сегодня отработал — иди восстанавливайся, блядь, нахуй, съешь 50 грам каша нахуй, бля, еба. Мышцам расти надо, а не просто так сидеть. По чуть-чуть, блядь, будешь делать — станешь сильнее, нахуй.`;
    }
  }

  /**
   * 3. Напоминание о тренировке (для Cron/Queue задач)
   */
  static getWorkoutReminderMessage(telegramId: number | string, firstName: string): string {
    const idStr = String(telegramId);
    switch (idStr) {
      case this.FRIEND_IDS.FADILA:
        return `🔔 Фадеев, подъем блять! Время ебошить в зале, нахуй!\n\nДавай, поднимай жопу, кроме тебя тут пример подавать некому, эти молодые без тебя совсем сдуются. Погнал в зал зайцем, нахуй!`;
      case this.FRIEND_IDS.ALBERT:
        return `🔔 Альберт, блядь! Хватит там свои энергетики баночные сосать!\n\nПоднимай жопу и пиздуй в зал. Поработаем без твоей химии, блядь, чтоб ты понял, что такое настоящая пахота, нахуй!`;
      case this.FRIEND_IDS.FJODOR:
        return `🔔 Фёдор, блядь, ты там опять затупил или на боксе посреди ринга уснул, нахуй?!\n\nХватит там на цепи сидеть и башкой удары ловить, блядь, поднимай жопу и пиздуй, нахуй, в зал! Хоть мышцы себе качнешь, чтоб хоть на человека похож стал, блядь! Жду в зале, блядь, нахуй, сука!`;
      case this.FRIEND_IDS.DIMA:
        return `🔔 Димон, блядь, сука, нахуй! Ты где опять шлындаешь, ебать?! Опять сидишь дома, жрёшь свой всратый раф, блядь, и выдумываешь хуйню, почему тебе сегодня "давление, сука, не позволяет" тяжёлое поднимать, а?! Поднимай свою ленивую жопу, блядь, и чеши в зал, нахуй! За тебя никто под штангу не ляжет, пидор ты эдакий! Жду в зале, быстро собрался и пригнал, ебошить пора, блядь!`;
      default:
        return `Слышь, ${firstName}.\n\nТы на тренировку собираешься вообще, блядь, нахуй? Занятие само себя не сделает. Вали в зал, блядь, хоть по чуть-чуть ебошить — чтоб хоть что-то с тобой происходить начало.`;
    }
  }
}